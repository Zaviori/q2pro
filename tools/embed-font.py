#!/usr/bin/env python3
"""Turn the client's TrueType fonts into a C file, so the client has them
built in as a fallback (src/refresh/text.c): the regular face and the
bold one, in that order.

    embed-font.py <out.c> <regular.ttf> <bold.ttf>
"""
import sys


def array(out, name, data):
    out.write(f"const unsigned char {name}[{len(data)}] = {{\n")
    for i in range(0, len(data), 20):
        out.write("    " + ",".join(str(b) for b in data[i:i + 20]) + ",\n")
    out.write("};\n")
    out.write(f"const unsigned {name}_len = {len(data)};\n\n")


def main():
    out_path, regular, bold = sys.argv[1:4]
    with open(out_path, "w") as out:
        out.write("// generated by tools/embed-font.py from %s and %s - do not edit\n\n"
                  % (regular.split("/")[-1], bold.split("/")[-1]))
        for name, path in (("text_builtin_regular", regular), ("text_builtin_bold", bold)):
            with open(path, "rb") as f:
                array(out, name, f.read())


main()
